#!/usr/bin/env python3
"""Generates the colour-scale block in styles.css (theme/palette.css).

Tailwind v4 reads every colour from --color-<family>-<stop> variables. This script writes
a :root block that overrides those variables so the whole app picks up the Hub palette
without changing any class names. Run: python3 scripts/build-theme.py
"""
import colorsys, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
STOPS = {50: 97, 100: 93, 200: 86, 300: 76, 400: 66, 500: 56, 600: 47, 700: 38, 800: 29, 900: 21, 950: 13}

# family -> (hue in degrees, saturation 0-1). Neutrals are a cool graphite; accent is warm amber.
FAMILIES = {
    'gray': (225, 0.12), 'slate': (222, 0.14), 'zinc': (240, 0.08),
    'amber': (38, 0.88), 'yellow': (46, 0.92), 'orange': (24, 0.85),
    'emerald': (38, 0.88), 'green': (150, 0.55), 'teal': (172, 0.60),
    'sky': (203, 0.88), 'blue': (217, 0.86), 'indigo': (224, 0.72),
    'violet': (252, 0.70), 'purple': (266, 0.62), 'fuchsia': (318, 0.62),
    'rose': (352, 0.74), 'red': (1, 0.76), 'pink': (330, 0.66),
}

def hex_of(h, s, l):
    r, g, b = colorsys.hls_to_rgb(h / 360, l / 100, s)
    return '#%02X%02X%02X' % (round(r * 255), round(g * 255), round(b * 255))

def build():
    names = set(re.findall(r'--color-([a-z]+)-(\d+)', (ROOT / 'vendor/tailwind.css').read_text()))
    lines = ['/* Generated by scripts/build-theme.py. Edit the FAMILIES table there, then re-run. */', ':root {']
    for fam, stop in sorted(names, key=lambda x: (x[0], int(x[1]))):
        if fam not in FAMILIES:
            continue
        h, s = FAMILIES[fam]
        lines.append(f'    --color-{fam}-{stop}: {hex_of(h, s, STOPS[int(stop)])};')
    lines.append('    --color-white: #FFFFFF;')
    lines.append('}')
    out = ROOT / 'theme-palette.css'
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('wrote', out, len(lines) - 3, 'variables')

if __name__ == '__main__':
    build()
